/**
 * Allowlist of files that may exist in `public/data/`.
 *
 * Everything under `public/data/` is served to every visitor, so a stray
 * backup, geocoder intermediate or scraper wrapper is dead weight at best and
 * a payload regression at worst. The budget gate (scripts/check-data-budget.mjs)
 * fails on any entry that is not listed here. To ship a new data file, add it
 * here in the same PR that adds the file.
 */
import { readdirSync } from 'node:fs';

export const ALLOWED_DATA_FILES = Object.freeze([
  '.gitkeep',
  'association_locations.json',
  'associations.json',
  'counties.geojson',
  'geometry-ledger-manifest.json',
  'geometry-ledger.json',
  'meta.json', // generated by scripts/gen-meta.mjs at prebuild (gitignored)
  'osm-lineage.json',
  'preview_class2_physical.json',
  'sector-evidence.json', // river geometry v2, task T4.3
  'uncontracted_lakes.json',
  'uncontracted_majors.json',
  'uncontracted_rivers.json',
  'waters.json',
  'waters_county_clips.json',
]);

/**
 * Files fetched lazily (after first paint / on demand). Their gzip size is
 * reported as INFO by the budget gate; they are not (yet) part of M7–M9.
 */
export const LAZY_DATA_FILES = Object.freeze([
  'geometry-ledger.json',
  'preview_class2_physical.json',
  'sector-evidence.json',
  'uncontracted_lakes.json',
  'uncontracted_rivers.json',
  'waters_county_clips.json',
]);

/**
 * BLOCKING gzip-9 caps (bytes) for lazy files. A lazy file without a cap is
 * INFO only.
 */
export const LAZY_GZIP_CAPS = Object.freeze({
  'sector-evidence.json': 300 * 1024, // river geometry v2, plan T4.3
});

/** `null` when within its cap (or uncapped), else a FAIL detail string. */
export function lazyCapViolation(file, gzipBytes, caps = LAZY_GZIP_CAPS) {
  const cap = caps[file];
  if (cap === undefined || gzipBytes <= cap) return null;
  return `${file} gzip-9 ${(gzipBytes / 1024).toFixed(1)} KB > cap ${(cap / 1024).toFixed(0)} KB`;
}

/**
 * Names present in `dataDir` that are not on the allowlist (directories
 * included), sorted. A missing directory yields an empty list.
 */
export function findUnexpectedFiles(dataDir, allowed = ALLOWED_DATA_FILES) {
  let entries;
  try {
    entries = readdirSync(dataDir);
  } catch (err) {
    if (err && err.code === 'ENOENT') return [];
    throw err;
  }
  const ok = new Set(allowed);
  return entries.filter((name) => !ok.has(name)).sort();
}
