"""Regression tests on real OSM geometry taken from the committed v1 index.

Fixtures are generated by ``python -m rivernet.fixtures_from_v1`` (ways only,
tagged waterway=river). NOTE: the v1 index is already decimated, so vertex
spacing of 2-8 km exists *inside single OSM ways* (e.g. Barcau 4.2 km, Olt
8.1 km). The invariant checked here is therefore "stitching adds no segment
longer than the source data already has", not an absolute 1 km cap; the
absolute cap must be re-checked on the full Geofabrik extract (owner step O3).
"""
from pathlib import Path

import pytest

from rivernet.courses import build_courses
from rivernet.extract_schema import load_extract
from rivernet.geodesy import vincenty_m
from rivernet.graph import build_graph
from rivernet.qa import qa_report

FIX = Path(__file__).resolve().parent.parent / "fixtures" / "rivernet"

# name -> (expected course length in m, how it was obtained)
# Obtained 2026-10-17 by running build_courses on the committed fixture itself
# (so it pins today's behaviour; the index is partial, e.g. Ialomita is ~417 km
# in reality but only 72 index ways are available).
EXPECTED_LENGTH_M = {
    "ialomita": 219590.5,
    "barcau": 115060.9,
    "bistrita": 233429.1,
    "olt_reach": 223800.3,
}


def build(name):
    ex = load_extract(FIX / f"{name}.jsonl.gz")
    wg = build_graph(ex)
    return ex, wg, build_courses(wg, ex)


def source_max_segment_m(ex):
    return max(
        vincenty_m(*w.coords[i], *w.coords[i + 1]) for w in ex.ways.values() for i in range(len(w.coords) - 1)
    )


@pytest.mark.parametrize("name", sorted(EXPECTED_LENGTH_M))
def test_fixture_builds_one_course_of_the_expected_length(name):
    _ex, _wg, courses = build(name)
    assert len(courses) == 1
    expected = EXPECTED_LENGTH_M[name]
    assert abs(courses[0].length_m - expected) / expected < 0.02


@pytest.mark.parametrize("name", sorted(EXPECTED_LENGTH_M))
def test_stitching_introduces_no_chord(name):
    ex, wg, courses = build(name)
    report = qa_report(wg, courses)
    assert report["max_segment_m_overall"] <= source_max_segment_m(ex) + 1.0
    # nothing was bridged synthetically in these fixtures
    assert report["synthetic_connectors"]["count"] == 0


def test_ialomita_and_barcau_have_no_long_chord_between_connected_ways():
    # Ialomita's own data never exceeds 1 km between vertices
    ex, wg, courses = build("ialomita")
    assert qa_report(wg, courses)["max_segment_m_overall"] < 1000
    # Barcau: the 51.4 km chord of the old pipeline is gone: the longest segment
    # is a single source-way segment (< 5 km), and course length ~ way length
    ex, wg, courses = build("barcau")
    assert qa_report(wg, courses)["max_segment_m_overall"] < 5000


def test_olt_reach_reports_but_does_not_bridge_reservoir_gaps():
    ex, wg, courses = build("olt_reach")
    assert not ex.areas  # the v1 index carries no areas
    assert all(not c.synthetic for c in courses)


def test_course_runs_upstream_to_downstream_without_backtracking():
    # Barcau flows west (lon decreases): the course must not jump around
    _ex, _wg, (course,) = build("barcau")
    lons = [c[0] for c in course.line.coords]
    assert lons[0] > lons[-1]
    assert all(b <= a + 0.02 for a, b in zip(lons, lons[1:]))  # no big eastward jump


@pytest.mark.parametrize("name", sorted(EXPECTED_LENGTH_M))
def test_output_is_deterministic(name):
    a = [c.to_record() for c in build(name)[2]]
    b = [c.to_record() for c in build(name)[2]]
    assert a == b


def test_fixture_sizes_stay_small():
    for name in EXPECTED_LENGTH_M:
        assert (FIX / f"{name}.jsonl.gz").stat().st_size < 1_500_000
